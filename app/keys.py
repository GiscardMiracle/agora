"""Per-user SSH keys used to clone repositories.

Each corrector owns one ed25519 key pair generated by the server. The private key never
leaves DATA_DIR/keys; the user only sees the public half, to register it on GitHub.
"""
import os
import subprocess
import tempfile
from pathlib import Path

from . import config


def private_path(user_id: int) -> Path:
    return config.KEYS_DIR / f"user_{int(user_id)}"


def has_key(user_id: int) -> bool:
    return private_path(user_id).is_file()


def generate(user_id: int, comment: str) -> str:
    """Create (or replace) the key pair and return the public key."""
    config.ensure_dirs()
    with tempfile.TemporaryDirectory(dir=config.KEYS_DIR) as tmp:
        target = Path(tmp) / "key"
        r = subprocess.run(
            ["ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-C", f"agora-{comment}", "-f", str(target)],
            capture_output=True, text=True, check=False,
        )
        if r.returncode != 0:
            raise RuntimeError(f"ssh-keygen failed: {r.stderr.strip()}")
        os.chmod(target, 0o600)
        pub = target.with_suffix(".pub").read_text().strip()
        os.replace(target, private_path(user_id))  # same filesystem: atomic
    return pub


def delete(user_id: int) -> None:
    private_path(user_id).unlink(missing_ok=True)


def ssh_command(user_id: int) -> str:
    return (
        f"ssh -i {private_path(user_id)} -o IdentitiesOnly=yes -o BatchMode=yes "
        "-o StrictHostKeyChecking=accept-new"
    )
